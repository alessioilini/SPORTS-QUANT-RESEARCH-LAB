#!/usr/bin/env python3
"""Generate MODEL_VALIDATION.md from reports/artifacts (numbers are never typed by hand)."""
import json
from pathlib import Path

import pandas as pd

from sportslab.config import ARTIFACTS_DIR, ROOT
from sportslab.research.validation import CFG

A = ARTIFACTS_DIR
m = pd.read_parquet(A / "metrics.parquet")
comp = pd.read_parquet(A / "comparisons.parquet")
tun = pd.read_parquet(A / "tuning.parquet")
summ = json.loads((A / "validation_summary.json").read_text())
bt = pd.read_parquet(A / "backtest_summary.parquet") if (A / "backtest_summary.parquet").exists() else None
cc = json.loads((A / "backtest_crosscheck.json").read_text()) if (A / "backtest_crosscheck.json").exists() else None
sim = pd.read_parquet(A / "season_simulation.parquet") if (A / "season_simulation.parquet").exists() else None

BENCH = ("market:", "external:")
out = []
w = out.append


def f4(x):
    return "—" if pd.isna(x) else f"{x:.4f}"


def pct(x):
    return "—" if pd.isna(x) else f"{100 * x:+.2f}%"


w("# MODEL_VALIDATION — Sports Quant Research Lab\n")
w("_Generated by `scripts/make_reports.py` from `reports/artifacts/`. Re-run `scripts/run_validation.py`, "
  "`scripts/run_backtest.py`, then this script to refresh. Do not edit numbers by hand._\n")
w("## 1. Protocol\n")
w("* **Chronological splits only** (no shuffling). Seasons per sport:\n")
w("| sport | burn-in | train | validation (tuning + calibration) | test (out-of-sample, touched once) |")
w("|---|---|---|---|---|")
for s, c in CFG.items():
    w(f"| {s} | {', '.join(c.burn_in)} | {', '.join(c.train)} | {', '.join(c.validation)} | {', '.join(c.test)} |")
w("")
w("* Every prediction comes from the walk-forward driver (`sportslab.models.base.walk_forward`). At each "
  "decision time it reveals only results with `available_at ≤ forecast_time`. Batch models refit on that "
  "history (Dixon-Coles weekly, logistic/GBM every 28 days).")
w("* Hyper-parameter grids are scored on the **validation season only** (test rows are removed during tuning). "
  "Calibration (temperature scaling, suffix `+temp`) is fitted on validation and applied unchanged to test.")
w("* Metrics: log loss (primary), multi-class Brier, accuracy, ECE (10 bins), RPS for football. 95% CIs come "
  "from a 2,000-sample bootstrap over matches. Model comparisons use a **paired** bootstrap of the per-match "
  "log-loss difference.")
w("* Benchmarks: `baseline:uniform`, `baseline:base-rate` (outcome frequencies known at the time), "
  "`baseline:rank-logit` (tennis). `market:pinnacle-opening` (known at forecast time; falls back to the market-average "
  "opening price for the 170 matches of 2025-26 without Pinnacle prices). "
  "`market:pinnacle-closing` / `market:pinnacle-single`: priced **after** the forecast time, so they are a "
  "reference only and have an information advantage. `external:fivethirtyeight`: a published third-party "
  "model that uses player availability data this lab does not have.\n")

for sport in CFG:
    t = m[(m.sport == sport)]
    if t.empty:
        continue
    w(f"## 2.{list(CFG).index(sport) + 1} {sport.capitalize()}\n")
    test = t[t.split == "test"].sort_values("log_loss")
    n = int(test.n.max())
    w(f"Test matches: **{n}** ({', '.join(CFG[sport].test)}).\n")
    cols = "| model | log loss [95% CI] | Brier | accuracy | ECE |" + (" RPS |" if sport == "football" else "")
    w(cols)
    w("|---|---|---|---|---|" + ("---|" if sport == "football" else ""))
    for r in test.itertuples():
        tag = " *(benchmark)*" if r.model.startswith(BENCH) else ""
        line = (f"| `{r.model}`{tag} | {r.log_loss:.4f} [{r.log_loss_lo:.4f}, {r.log_loss_hi:.4f}] | "
                f"{r.brier:.4f} | {r.accuracy:.3f} | {r.ece:.3f} |")
        if sport == "football":
            line += f" {r.rps:.4f} |"
        w(line)
    w("")
    # train vs OOS gap
    piv = t.pivot_table(index="model", columns="split", values="log_loss")
    piv = piv[[c for c in ("train", "validation", "test") if c in piv]]
    core = [x for x in piv.index if not x.endswith("+temp") and not x.startswith(("baseline:uniform",))]
    w("**Train → validation → test log loss** (in-sample walk-forward vs out-of-sample):\n")
    w("| model | train | validation | test | test − train |")
    w("|---|---|---|---|---|")
    for mod in core:
        r = piv.loc[mod]
        w(f"| `{mod}` | {f4(r.get('train'))} | {f4(r.get('validation'))} | {f4(r.get('test'))} | "
          f"{f4(r.get('test') - r.get('train')) if pd.notna(r.get('train')) else '—'} |")
    w("")
    c = comp[(comp.sport == sport)]
    w("**Paired comparison on test** (Δ log loss = model − reference; negative = model better; "
      "`p_better` = bootstrap share with Δ<0):\n")
    w("| model | reference | n | Δ log loss | 95% CI | p_better | verdict |")
    w("|---|---|---|---|---|---|---|")
    for r in c[~c.model.str.endswith("+temp")].sort_values(["reference", "mean_diff"]).itertuples():
        verdict = ("better (CI < 0)" if r.hi < 0 else "worse (CI > 0)" if r.lo > 0 else "not distinguishable")
        w(f"| `{r.model}` | `{r.reference}` | {r.n} | {r.mean_diff:+.4f} | [{r.lo:+.4f}, {r.hi:+.4f}] | "
          f"{r.p_better:.2f} | {verdict} |")
    w("")
    tt = tun[tun.sport == sport]
    if not tt.empty:
        w("**Tuned hyper-parameters (validation log loss)**:\n")
        for mod, g in tt.groupby("model"):
            g = g.dropna(axis=1, how="all").sort_values("val_log_loss")
            params = [k for k in g.columns if k not in ("val_log_loss", "model", "sport")]
            best = g.iloc[0]
            edges = [k for k in params if best[k] in (g[k].min(), g[k].max()) and g[k].nunique() > 1]
            w(f"* `{mod}`: " + ", ".join(f"{k}={best[k]:g}" for k in params) +
              f" (val LL {best.val_log_loss:.4f}; {len(g)} combos)" +
              (f" — ⚠️ at grid edge: {', '.join(edges)}" if edges else ""))
        w("")
    temps = summ.get("calibrators", {}).get(sport, {})
    if temps:
        w("**Temperature (fitted on validation; T>1 = model was over-confident)**: " +
          ", ".join(f"`{k}` {v:.2f}" for k, v in sorted(temps.items())) + "\n")

w("## 3. Live model validation (real EPL half-time data)\n")
lv = summ.get("live_ht", {})
if lv:
    w(f"Parameters estimated on the **train seasons only**: second-half share of goals = "
      f"**{lv['second_half_share']:.3f}**, Bayesian prior weight (in match-equivalents) = "
      f"**{lv['prior_weight']:.1f}**. Red-card multipliers and the hockey power-play multipliers are literature "
      "ASSUMPTIONS (the lab has no minute-level event data), flagged as such in `sportslab/live/engine.py`.\n")
    w("| split | n | pre-match LL | live@HT LL | Δ LL [95% CI] | pre-match Brier | live@HT Brier |")
    w("|---|---|---|---|---|---|---|")
    for split in ("train", "validation", "test"):
        b = lv["by_split"].get(split)
        if b:
            d = b["diff_ll"]
            w(f"| {split} | {b['n']} | {b['prematch']['log_loss']:.4f} | {b['live_ht']['log_loss']:.4f} | "
              f"{d['mean_diff']:+.4f} [{d['lo']:+.4f}, {d['hi']:+.4f}] | {b['prematch']['brier']:.4f} | "
              f"{b['live_ht']['brier']:.4f} |")
    w("")
bs = summ.get("basketball_live_sigma")
if bs:
    w(f"NBA live final-margin dispersion σ = **{bs['sigma_full']:.2f} points**, estimated by maximum likelihood on "
      f"{bs['n_games']} FiveThirtyEight nba-elo home games (2005-2015).\n")
w("Feed-latency handling is tested in `tests/test_live.py`: `OK` → `DELAYED` (with delay seconds) → "
  "`INSUFFICIENT_DATA`. The engine never reports `OK` when the source timestamp is unknown.\n")

w("## 4. Monte Carlo\n")
mc = summ.get("montecarlo", {})
if mc:
    w(f"* Exact-score sampling vs analytic Dixon-Coles probabilities on {mc['n_matches']} real test fixtures "
      f"({mc['sims_per_match']:,} sims each): max |error| = **{mc['max_abs_err_vs_analytic']:.4f}**, mean "
      f"{mc['mean_abs_err']:.4f}.")
    w(f"* Same seed → identical results: **{mc['same_seed_identical']}**; different seed → different draws: "
      f"**{mc['different_seed_differs']}**.")
if sim is not None:
    inside = int(sim.within_90pct.sum())
    w(f"* Season simulation EPL 2025-26 from {sim.as_of.iloc[0]} ({int(sim.n_sims.iloc[0]):,} runs, seed "
      f"{int(sim.seed.iloc[0])}): actual final points fell inside the 90% interval for **{inside}/{len(sim)}** "
      f"teams (≈{0.9 * len(sim):.0f} expected if calibrated). Simulated favourite: **{sim.iloc[0].team}** "
      f"(P(title)={sim.iloc[0].p_title:.2f}). Actual champion: "
      f"**{sim.sort_values('actual_points', ascending=False).iloc[0].team}**.")
w("")

if bt is not None:
    w("## 5. Strategy research (virtual bankroll, historical)\n")
    w("Prices: football = Pinnacle **opening** odds (known at forecast time), with CLV measured against Pinnacle "
      "closing. Tennis = Pinnacle single pre-match snapshot (timestamp unknown, so no CLV). One virtual position "
      "per event: the outcome with the highest EV after any haircut, only if EV ≥ 3%. Odds range 1.01–8.0. "
      "All amounts are **virtual units**.\n")
    w("| sport | model | period | strategy | positions | virtual ROI [95% CI] | P(ROI>0) | virtual P&L | max DD | hit rate (exp.) | CLV |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    show = bt[bt.strategy.isin(["fixed-1u", "fixed-1u+uncertainty-k1", "fraction-2pct+dd-stop-25pct"]) &
              (bt.n_positions > 0)]
    for r in show.sort_values(["sport", "model", "strategy", "period"]).itertuples():
        clv = getattr(r, "clv_mean", float("nan"))
        w(f"| {r.sport} | `{r.model}` | {r.period} | {r.strategy} | {r.n_positions} | {pct(r.virtual_roi)} "
          f"[{pct(r.virtual_roi_ci_lo)}, {pct(r.virtual_roi_ci_hi)}] | {r.p_roi_positive:.2f} | "
          f"{r.virtual_pnl:+.1f} | {r.max_drawdown:.1%} | {r.hit_rate:.3f} ({r.expected_hit_rate:.3f}) | "
          f"{pct(clv) if pd.notna(clv) else '—'} |")
    w("")
    w("Virtual starting bankroll: 1,000 units. `fixed-1u` = 1 unit per position. "
      "`fraction-2pct+dd-stop-25pct` = 2% of the settled bankroll, halted after a 25% drawdown from peak. "
      "`uncertainty-k1` requires EV ≥ 3% after subtracting 1× the across-model spread from the probability.")
    w("")
    mk = bt[bt.model.str.startswith("market:")]
    if len(mk):
        w(f"Control: the de-vigged market judged against its own prices selected **{int(mk.n_positions.sum())}** "
          "positions (its EV is always minus the margin), which confirms the selection logic.\n")
    w("The `fraction-1pct` and `fixed-1u+commission-2pct` variants are in "
      "`reports/artifacts/backtest_summary.parquet` and in the dashboard (Backtesting, Virtual Bankroll).\n")
    sel = bt[(bt.n_positions > 0) & (bt.strategy == "fixed-1u")]
    w(f"**Adverse selection:** on the positions selected (`fixed-1u`), the realised hit rate averaged "
      f"**{sel.hit_rate.mean():.3f}**, while the model expected **{sel.expected_hit_rate.mean():.3f}**. When a model "
      "disagrees with a sharp price by ≥3%, the model is usually the one that is wrong. The consistently negative "
      "CLV in football (the price taken is worse than the closing fair price) points the same way.\n")
    if cc:
        ok = all(c["abs_diff"] < 1e-6 and c["n"] == c["backtestbuddy_bets"] for c in cc["crosscheck"])
        w(f"**Independent cross-check:** flat 1-unit P&L recomputed with `backtestbuddy` on the same selections "
          f"for {len(cc['crosscheck'])} model/sport combinations. Identical: **{ok}** "
          f"(max |diff| = {max(c['abs_diff'] for c in cc['crosscheck']):.2e}). Virtual journal run: `{cc['run_id']}`.\n")

w("## 6. Conclusions (read with the CIs)\n")
for sport in CFG:
    t = m[(m.sport == sport) & (m.split == "test")]
    if t.empty:
        continue
    own = t[~t.model.str.startswith(BENCH + ("baseline:",))].sort_values("log_loss").iloc[0]
    bench = t[t.model.str.startswith(BENCH)].sort_values("log_loss")
    line = f"* **{sport}** — best lab model on test: `{own.model}` (LL {own.log_loss:.4f})"
    br = comp[(comp.sport == sport) & (comp.model == own.model) & (comp.reference == "baseline:base-rate")]
    if not br.empty:
        b = br.iloc[0]
        line += f"; vs base-rate Δ={b.mean_diff:+.4f} [{b.lo:+.4f}, {b.hi:+.4f}]"
    for r in bench.itertuples():
        cr = comp[(comp.sport == sport) & (comp.model == own.model) & (comp.reference == r.model)]
        if not cr.empty:
            x = cr.iloc[0]
            line += (f"; vs `{r.model}` (LL {r.log_loss:.4f}) Δ={x.mean_diff:+.4f} [{x.lo:+.4f}, {x.hi:+.4f}]")
    w(line + ".")
w("")
w("General reading: the lab's models clearly beat naive baselines in every sport. They do **not** beat sharp "
  "closing prices or FiveThirtyEight (which uses injury and roster information). In the strategy research, "
  "any positive virtual ROI must be judged against its bootstrap CI and the in-sample vs out-of-sample gap; a "
  "CI that includes zero is not evidence of an edge.\n")
w("## 7. Limitations\n")
w("* Lineups, injuries and minute-level events are UNKNOWN for every sport (no verifiable free source was "
  "reachable). Live models fill these gaps with stated assumptions instead of data.\n"
  "* Hockey and basketball have no historical odds, so there is no market benchmark or backtest. NBA results have "
  "no scores, so no goal/points model.\n"
  "* Tennis 2024 is incomplete in the mirror (1,813 matches; the second-half hard-court swing is missing). "
  "Tennis odds have no timestamp, so tennis backtests use a single snapshot that is probably close to closing, "
  "and CLV cannot be computed.\n"
  "* Some tuned hyper-parameters sit at the edge of their grid (flagged ⚠️ above), so the optimum may lie outside "
  "the grid. The grids were not widened after looking at test results, to keep the test set untouched.\n"
  "* The football forecast time uses the provider's documented odds-collection schedule (Fri/Tue afternoon, "
  "approximate), not an exact timestamp.\n")
(ROOT / "MODEL_VALIDATION.md").write_text("\n".join(out))
print(f"wrote MODEL_VALIDATION.md ({len(out)} lines)")
